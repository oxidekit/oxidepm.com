def strip_term(line):
    return re.sub(r"\{(hi|ox|dim|b):(.*?)\}", r"\2", line)


def absolute_links(line):
    return re.sub(r"\]\((/[^)\s]*)\)", lambda m: "](%s%s)" % (SITE, m.group(1)), line)


def md_export(text):
    """The Markdown of a docs source for people and tools that read Markdown: the page-only
    blocks (terminal captures, titled code, notes, field lists) become plain Markdown."""
    lines = text.split("\n")
    out = []
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        m = re.match(r"^```(\S*)\s*(.*)$", line)
        if m:
            lang, rest = m.group(1), m.group(2)
            body = []
            i += 1
            while i < n and not lines[i].startswith("```"):
                body.append(lines[i])
                i += 1
            i += 1
            opts = dict(re.findall(r'(\w+)="([^"]*)"', rest))
            if lang == "term":
                if "cap" in opts:
                    body = read(SRC / "captures" / (opts["cap"] + ".txt")).rstrip("\n").split("\n")
                body = [strip_term(l) for l in body]
                if opts.get("label"):
                    out += ["*%s*" % opts["label"], ""]
                lang = "text"
            elif opts.get("title"):
                out += ["*%s*" % opts["title"], ""]
            out += ["```" + lang] + body + ["```"]
            continue
        if line.startswith("::: "):
            kind = line[4:].strip()
            body = []
            i += 1
            while i < n and lines[i].strip() != ":::":
                body.append(lines[i])
                i += 1
            i += 1
            if kind.startswith("note"):
                label = kind[4:].strip() or "Note"
                inner = md_export("\n".join(body)).split("\n")
                inner[0] = "**%s.** %s" % (label, inner[0]) if inner and inner[0] else "**%s.**" % label
                out += ["> " + l if l else ">" for l in inner]
            elif kind == "fields":
                items = []
                for fl in body:
                    if not fl.strip():
                        continue
                    if fl.startswith(": "):
                        items[-1]["desc"].append(fl[2:])
                    else:
                        items.append({"head": [x.strip() for x in fl.split(" | ")], "desc": []})
                for it in items:
                    extra = ", ".join(it["head"][1:])
                    head = "`%s`" % it["head"][0] + (" (%s)" % extra if extra else "")
                    out.append("- %s: %s" % (head, " ".join(it["desc"])))
            continue
        out.append(absolute_links(line))
        i += 1
    return "\n".join(out)


def doc_markdown(p, canonical, source):
    return "# %s\n\n%s\n\nSource: %s\n\n%s\n" % (
        p["title"], absolute_links(p["summary"]), canonical, md_export(source).strip("\n"))


