class Site:
    def __init__(self):
        self.layout = read(SRC / "partials" / "layout.html")
        self.header = read(SRC / "partials" / "header.html")
        self.footer = read(SRC / "partials" / "footer.html")
        self.urls = []

    def page(self, path, title, description, body, nav="", noindex=False, out=None,
             og_type="website", jsonld=None, alternate=None, modified=None):
        header = fill(self.header, {"nav_links": nav_html(nav), "menu_links": menu_html(nav)})
        canonical = SITE + path
        robots = '<meta name="robots" content="noindex">\n' if noindex else '<meta name="robots" content="index, follow, max-image-preview:large">\n'
        alt = '<link rel="alternate" type="text/markdown" href="%s">\n' % (SITE + alternate) if alternate else ""
        for label, value, low, limit in (("title", title, 0, 70), ("description", description, 70, 165)):
            if (len(value) > limit or len(value) < low) and not noindex:
                print("warning: %s of %s is %d characters" % (label, path, len(value)), file=sys.stderr)
        text = fill(self.layout, {
            "title": esc(title),
            "description": esc(description),
            "canonical": canonical,
            "robots": robots,
            "og_type": og_type,
            "image": IMAGE,
            "image_alt": esc(IMAGE_ALT),
            "alternate": alt,
            "jsonld": jsonld_html(jsonld or []),
            "header": header,
            "footer": self.footer,
            "body": body,
        })
        if out is None:
            out = (path.lstrip("/") + "index.html") if path.endswith("/") else path.lstrip("/")
        write(out, text)
        if not noindex:
            self.urls.append((canonical, modified or today()))


