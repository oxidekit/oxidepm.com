def nav_html(current, cls=""):
    items = []
    for key, label, href in NAV_LINKS:
        cur = ' aria-current="page"' if key == current else ""
        items.append('      <a href="%s"%s>%s</a>' % (href, cur, label))
    return "\n".join(items)


def menu_html(current):
    items = []
    for key, label, href in NAV_LINKS:
        cur = ' aria-current="page"' if key == current else ""
        items.append('    <a href="%s"%s>%s</a>' % (href, cur, label))
    return "\n".join(items)


def today():
    return datetime.date.today().isoformat()


def lastmod(*sources):
    """The date of the last commit that touched the sources, or today when one has uncommitted
    changes or is not in git yet. The same inputs give the same date once they are committed."""
    rels = [str(Path(s).resolve().relative_to(ROOT)) for s in sources]
    try:
        dirty = subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain", "--"] + rels,
                               capture_output=True, text=True, check=True).stdout.strip()
        if dirty:
            return today()
        day = subprocess.run(["git", "-C", str(ROOT), "log", "-1", "--format=%cs", "--"] + rels,
                             capture_output=True, text=True, check=True).stdout.strip()
        return day or today()
    except (OSError, subprocess.CalledProcessError):
        return today()


def jsonld_html(objects):
    out = []
    for obj in objects:
        text = json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
        out.append('<script type="application/ld+json">%s</script>\n' % text)
    return "".join(out)


